import { useEffect, useState } from 'react'
import { Check, ClipboardCopy, Download, FileText, Printer } from 'lucide-react'
import type { MathModel } from '../../core/types'
import { buildConclusion, buildReport, toHtml, toMarkdown, toPlain } from '../../core/conclusion'
import { models, toast, useStore } from '../../store/store'
import { tr } from '../../core/text'
import { Btn, Label } from '../common'
import type { Working } from './working'

const slug = (s: string) => s.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 50) || 'model'

function download(name: string, text: string, type: string) {
  const url = URL.createObjectURL(new Blob([text], { type }))
  const a = document.createElement('a')
  a.href = url; a.download = name; document.body.appendChild(a); a.click(); a.remove()
  setTimeout(() => URL.revokeObjectURL(url), 1000)
}

/** Prints through a hidden iframe so no pop-up is needed; the user can choose "Save as PDF" in the print dialog. */
function printHtml(html: string) {
  const f = document.createElement('iframe')
  f.style.cssText = 'position:fixed;right:0;bottom:0;width:0;height:0;border:0'
  document.body.appendChild(f)
  const d = f.contentDocument!
  d.open(); d.write(html); d.close()
  setTimeout(() => { f.contentWindow?.focus(); f.contentWindow?.print(); setTimeout(() => f.remove(), 2000) }, 250)
}

export default function ConclusionPanel({ model, w }: { model: MathModel; w: Working }) {
  const lang = useStore((s) => s.ui.lang)
  const L = (en: string, es: string) => tr(lang, en, es)
  const [note, setNote] = useState(model.userConclusion ?? '')
  const [copied, setCopied] = useState<'' | 'c' | 'r'>('')
  useEffect(() => { setNote(model.userConclusion ?? '') }, [model.id, model.userConclusion])
  const c = buildConclusion(model, w.params, w.spec, lang)
  const report = buildReport(model, w.params, w.spec, lang, note)
  const footer = L('Generated by MATHEMA. This is a hypothesis built from stated assumptions; it is not evidence and not professional advice.', 'Generado por MATHEMA. Es una hipótesis construida con supuestos declarados; no es evidencia ni asesoramiento profesional.')
  const conclusionOnly = { title: model.title, sections: report.sections.filter((s) => s.h === L('Conclusion (hypothesis)', 'Conclusión (hipótesis)') || s.h === L('My own conclusion', 'Mi propia conclusión') || s.h === L('Caveats', 'Advertencias')) }
  const copy = async (what: 'c' | 'r') => {
    const text = toPlain(what === 'c' ? conclusionOnly : report)
    try { await navigator.clipboard.writeText(text); setCopied(what); setTimeout(() => setCopied(''), 1400) } catch { toast(L('The browser blocked copying. Use “Download” instead.', 'El navegador bloqueó el copiado. Usá «Descargar».'), 'warn') }
  }
  return (
    <section className="rounded-xl border border-accent/40 bg-surface p-4" aria-labelledby="concl-h">
      <div className="mb-1 flex flex-wrap items-center justify-between gap-2">
        <div id="concl-h"><Label>{L('Conclusion', 'Conclusión')}</Label></div>
        <span className="-mt-1 rounded-full bg-[rgb(var(--warn)/.14)] px-2 py-0.5 text-[11px] font-medium text-warn">{L('Hypothesis, not a finding', 'Hipótesis, no un hallazgo')}</span>
      </div>
      <p className="serif text-[19px] leading-snug">{c.headline}</p>
      {c.points.length > 0 && <ul className="mt-2 list-disc space-y-1 pl-5 text-[13.5px]">{c.points.map((p, i) => <li key={i}>{p}</li>)}</ul>}
      <p className="mt-3 text-xs text-mute">{L('It updates as you move the sliders. Open “Caveats” in the report for what it does not tell you.', 'Se actualiza al mover los deslizadores. El informe incluye las advertencias sobre lo que no te dice.')}</p>

      <label className="mt-4 block text-[13px] font-medium" htmlFor="my-concl">{L('My own conclusion (optional)', 'Mi propia conclusión (opcional)')}</label>
      <textarea id="my-concl" value={note} rows={3} maxLength={4000} onChange={(e) => setNote(e.target.value)} onBlur={() => { if (note !== (model.userConclusion ?? '')) models.setConclusion(model.id, note) }}
        placeholder={L('Write what you conclude from this model, in your own words…', 'Escribí qué concluís de este modelo, con tus palabras…')}
        className="mt-1 w-full rounded-lg border border-line bg-bg p-2.5 text-sm outline-none focus:border-accent" />

      <div className="mt-3 flex flex-wrap items-center gap-1.5">
        <Btn size="sm" variant="outline" onClick={() => copy('c')}>{copied === 'c' ? <Check size={14} /> : <ClipboardCopy size={14} />}{L('Copy conclusion', 'Copiar conclusión')}</Btn>
        <Btn size="sm" variant="outline" onClick={() => copy('r')}>{copied === 'r' ? <Check size={14} /> : <FileText size={14} />}{L('Copy full report', 'Copiar informe completo')}</Btn>
        <Btn size="sm" variant="outline" onClick={() => download(`${slug(model.title)}.md`, toMarkdown(report, footer), 'text/markdown;charset=utf-8')}><Download size={14} />{L('Download .md', 'Descargar .md')}</Btn>
        <Btn size="sm" variant="outline" onClick={() => download(`${slug(model.title)}.html`, toHtml(report, footer, lang), 'text/html;charset=utf-8')}><Download size={14} />{L('Download .html', 'Descargar .html')}</Btn>
        <Btn size="sm" variant="outline" onClick={() => printHtml(toHtml(report, footer, lang))}><Printer size={14} />{L('Print / PDF', 'Imprimir / PDF')}</Btn>
      </div>
    </section>
  )
}
